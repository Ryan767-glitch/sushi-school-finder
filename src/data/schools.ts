export function getSchool(slug: string) {
  return schools.find((s) => s.slug === slug);
}

export function schoolCount() {
  return schools.length;
}

export function featuredSchools() {
  return schools.filter((s) => s.badges.length > 0).slice(0, 6);
}

export function mapsUrl(school: School) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(school.mapsQuery)}`;
}

export function embedMapsUrl(school: School) {
  return `https://maps.google.com/maps?q=${encodeURIComponent(school.mapsQuery)}&z=15&output=embed`;
}
